"""Generate deterministic integer math tables; no firmware or hardware access."""
import math
from pathlib import Path
HERE=Path(__file__).resolve().parent
tables={
 'disc_hann':[round(32767*(.5-.5*math.cos(2*math.pi*i/1023))) for i in range(1024)],
 'disc_cos':[round(32767*math.cos(-2*math.pi*i/1024)) for i in range(512)],
 'disc_sin':[round(32767*math.sin(-2*math.pi*i/1024)) for i in range(512)],
 'disc_edges':[round((50*(16000/50)**(i/72))*65536/48000) for i in range(73)],
}
text=['/* Generated by generate_spectrum_tables.py. Q15 FFT/window, Q16 band edges. */']
for name,values in tables.items():
 text.append(f'static const {"unsigned short" if name=="disc_edges" else "short"} {name}[{len(values)}]={{')
 text.extend(' '+','.join(map(str,values[i:i+16]))+',' for i in range(0,len(values),16))
 text.append('};')
(HERE/'spectrum_tables.h').write_text('\n'.join(text)+'\n',encoding='utf-8')
