"""Reproduce the Tube2 core from pinned, unmodified MIT upstream sources.

Only the plugin shell, channel layout and coefficient caching change. The high
sample rate E/F history behavior deliberately remains exactly as upstream.
"""
from pathlib import Path
import hashlib
import json
import re
import shutil

P = Path(__file__).resolve().parent
U = P / 'third_party/airwindows-tube2'
T = P / 'tests_warmgloss'
lock = json.loads((U / 'source-lock.json').read_text())
for name, expected in lock['files'].items():
    source = U / ('AIRWINDOWS-LICENSE' if name == 'LICENSE' else Path(name).name)
    assert hashlib.sha256(source.read_bytes()).hexdigest() == expected, source
T.mkdir(exist_ok=True)
source = (U / 'Tube2Proc.cpp').read_text()
body = source[source.index('void Tube2::processDoubleReplacing'):]
body = body[body.index('{') + 1:body.rfind('}')]
_, loop = body.split('    while (--sampleFrames >= 0)', 1)
for name in ('previousSampleA', 'previousSampleB', 'previousSampleC',
             'previousSampleD', 'previousSampleE', 'previousSampleF', 'fpdL', 'fpdR'):
    loop = re.sub(r'\b' + name + r'\b', 's->' + name, loop)
for pointer in ('in1', 'in2', 'out1', 'out2'):
    loop = loop.replace(pointer + '++;', pointer + ' += 2;')
prefix = '''/* Airwindows Tube2 by Chris Johnson, MIT. Generated by generate_tube2_core.py.
 * Source and license: third_party/airwindows-tube2, source-lock.json.
 * Original double processing arithmetic retained, with cached coefficients and
 * an interleaved adapter. Fixed equal RNG seeds preserve channel symmetry.
 * The upstream high-rate history behavior is intentionally unchanged.
 * Compile this translation unit with -ffp-contract=off.
 */
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <math.h>
#include "tube2_core.h"
#include "tube2_core_state.h"
static void configure(DiscTube2 *s, unsigned rate, double input_pad, double tube) {
    s->rate = rate;
    s->A = (float)input_pad;
    s->B = (float)tube;
    s->fpdL = s->fpdR = 16386u;
    s->overallscale = 1.0;
    s->overallscale /= 44100.0;
    s->overallscale *= s->rate;
    double iterations = 1.0-s->B;
    s->powerfactor = (9.0*iterations)+1;
    s->asymPad = (double)s->powerfactor;
    s->gainscaling = 1.0/(double)(s->powerfactor+1);
    s->outputscaling = 1.0 + (1.0/(double)(s->powerfactor));
}
DiscTube2 *disc_tube2_create(unsigned rate, double input_pad, double tube) {
    if(rate < 8000 || rate > 384000 || !isfinite(input_pad) || !isfinite(tube)
       || input_pad < 0 || input_pad > 1 || tube < 0 || tube > 1) return NULL;
    DiscTube2 *s = calloc(1,sizeof(*s));
    if(s) configure(s,rate,input_pad,tube);
    return s;
}
void disc_tube2_destroy(DiscTube2 *s) { free(s); }
void disc_tube2_reset(DiscTube2 *s) {
    if(!s) return;
    unsigned rate=(unsigned)s->rate;
    double a=s->A,b=s->B;
    memset(s,0,sizeof(*s));
    configure(s,rate,a,b);
}
unsigned disc_tube2_memory(const DiscTube2 *s) { return s ? sizeof(*s) : 0; }
void disc_tube2_process_double(DiscTube2 *s, const double *inputs, double *outputs,
                               int sampleFrames) {
    if(!s || !inputs || !outputs || sampleFrames <= 0) return;
    const double *in1=inputs,*in2=inputs+1;
    double *out1=outputs,*out2=outputs+1;
    double overallscale=s->overallscale;
    double inputPad=s->A;
    int powerfactor=s->powerfactor;
    double asymPad=s->asymPad;
    double gainscaling=s->gainscaling;
    double outputscaling=s->outputscaling;
'''
suffix = '''}
void disc_tube2_sample_double(DiscTube2 *s, double io[2]) {
    disc_tube2_process_double(s,io,io,1);
}
'''
(P / 'tube2_core.c').write_text(prefix + '    while (--sampleFrames >= 0)' + loop + suffix,
                                encoding='utf-8', newline='\n')
# The oracle compiles this byte-for-byte upstream file against a tiny VST shim.
shutil.copy2(U / 'Tube2Proc.cpp', T / 'Tube2Proc.cpp')
print('Generated Tube2 double core from verified pinned MIT sources')
