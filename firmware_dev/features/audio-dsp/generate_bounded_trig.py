"""Inline the pinned musl/Sun kernels for StereoFX's already-clamped angles."""
from pathlib import Path
import hashlib,json
P=Path(__file__).resolve().parent;U=P/'third_party/musl-bounded-trig'
lock=json.loads((U/'source-lock.json').read_text())
out=['/* Generated by generate_bounded_trig.py. StereoFX-only bounded angles.\n'
     ' * Original Sun notices and kernel expressions preserved below.\n'
     ' * Never replaces process-wide libm; double precision, no FP contraction. */\n'
     '#ifndef DISC_STEREOFX_BOUNDED_TRIG_H\n#define DISC_STEREOFX_BOUNDED_TRIG_H\n']
for name in ('__sin','__cos'):
 b=(U/(name+'.c')).read_bytes();assert hashlib.sha256(b).hexdigest()==lock['files']['src/math/'+name+'.c']['sha256']
 s=b.decode().replace('#include "libm.h"','').replace('double_t','double')
 s=s.replace('double '+name+'(', 'static __attribute__((always_inline)) inline double disc_sf_kernel_'+name[2:]+'(')
 out.append(s)
out.append('''
/* Upstream StereoFX clamps every trigonometric argument to 1.57079633.
 * For x > pi/4, subtract a split pi/2: x-hi is exact by Sterbenz's
 * lemma over this interval. Renormalize the remainder so that the
 * kernel tail remains below one ulp of its main argument.
 * Outside that contract (including NaN), use the original system libm.
 */
static __attribute__((always_inline)) inline double disc_sf_sin(double x){
 if(!(x>=0.0&&x<=1.57079633))return sin(x);
 if(x<0x1p-27)return x;
 if(x<=0.78539816339744830962)return disc_sf_kernel_sin(x,0.0,0);
 double r=x-1.57079632679489655800,main=r-6.12323399573676603587e-17;
 double tail=(r-main)-6.12323399573676603587e-17;
 return disc_sf_kernel_cos(main,tail);
}
static __attribute__((always_inline)) inline double disc_sf_cos(double x){
 if(!(x>=0.0&&x<=1.57079633))return cos(x);
 if(x<0x1p-27)return 1.0;
 if(x<=0.78539816339744830962)return disc_sf_kernel_cos(x,0.0);
 double r=x-1.57079632679489655800,main=r-6.12323399573676603587e-17;
 double tail=(r-main)-6.12323399573676603587e-17;
 return -disc_sf_kernel_sin(main,tail,1);
}
#endif
''')
(P/'stereofx_bounded_trig.h').write_text('\n'.join(out))
print('Generated bounded double kernels with retained Sun licenses')
