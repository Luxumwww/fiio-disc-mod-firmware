func utf16Text(s string) []uint16 { return utf16.Encode([]rune(s)) }

func (s *server) metadataProvider(source string) provider.MusicProvider {
	b, _ := os.ReadFile(filepath.Join(s.credentials, source+".cookie"))
	switch source {
	case "netease":
		return netease.New(strings.TrimSpace(string(b)))
	case "qq":
		return qq.New(strings.TrimSpace(string(b)))
	case "kugou":
		return kugou.New(strings.TrimSpace(string(b)))
	}
	return nil
}
func (s *server) downloadCover(ctx context.Context, source, u string) []byte {
	if u == "" {
		return nil
	}
	pixels := s.coverPixelsFor(ctx, source, u, 480)
	if len(pixels) != 480*480*4 {
		return nil
	}
	im := image.NewRGBA(image.Rect(0, 0, 480, 480))
	for i := 0; i < len(pixels); i += 4 {
		im.Pix[i] = pixels[i+2]
		im.Pix[i+1] = pixels[i+1]
		im.Pix[i+2] = pixels[i]
		im.Pix[i+3] = 255
	}
	var b bytes.Buffer
	if jpeg.Encode(&b, im, &jpeg.Options{Quality: 85}) != nil {
		return nil
	}
	return b.Bytes()
}
func lrcForNative(raw string) []byte {
	lines := parseLyrics(raw)
	if len(lines) == 0 {
		return nil
	}
	var b strings.Builder
	for _, l := range lines {
		fmt.Fprintf(&b, "[%02d:%02d.%02d]%s\n", l.Millis/60000, l.Millis/1000%60, l.Millis/10%100, l.Text)
	}
	return []byte(b.String())
}

// Auxiliary fetch/write failure never discards a completed music download.
// JPEG and same-basename LRC are useful outside this player too. FLAC/MP3 also
// embed the cover for native album-art readers; compressed audio is copied.
func (s *server) saveDownloadMetadata(ctx context.Context, task downloadTask, song model.Song, path string) {
	if song.Source == "" {
		song.Source = task.Source
	}
	// Independent credential snapshot; enrich downloads only, not playback or
	// scrolling. Existing catalog values remain usable if the API is unavailable.
	if s.downloadLyric == nil && ctx.Err() == nil {
		if p, ok := s.metadataProvider(task.Source).(interface {
			GetSongMetadata(*model.Song) (*model.Song, error)
		}); ok {
			if detail, e := p.GetSongMetadata(&song); e == nil && detail != nil && detail.ID == song.ID && detail.Source == task.Source {
				song = mergeSongMetadata(song, *detail)
			}
		}
	}
	stem := strings.TrimSuffix(path, filepath.Ext(path))
	cover := s.downloadCover(ctx, task.Source, song.Cover)
	if len(cover) > 0 {
		if _, e := os.Lstat(stem + ".jpg"); os.IsNotExist(e) {
			diskAtomicWrite(stem+".jpg", cover)
		}
	}
	if song.ID != "" && ctx.Err() == nil {
		var raw string
		var e error
		if s.downloadLyric != nil {
			raw, e = s.downloadLyric(song, task.Source)
		} else if p := s.metadataProvider(task.Source); p != nil {
			raw, e = p.GetLyrics(&song)
		}
		if e == nil && len(raw) <= 512<<10 {
			if lrc := lrcForNative(raw); len(lrc) > 0 {
				if _, e := os.Lstat(stem + ".lrc"); os.IsNotExist(e) {
					diskAtomicWrite(stem+".lrc", lrc)
				}
			}
		}
	}
	if ctx.Err() == nil {
		if st, e := os.Lstat(stem + ".lrc"); e == nil && st.Mode().IsRegular() && st.Size() <= 512<<10 {
			if b, e := os.ReadFile(stem + ".lrc"); e == nil {
				song = cloneSong(song)
				song.Extra["lyrics"] = string(b)
			}
		}
		embedDownloadMetadata(path, song, cover)
	}
}

// Backfill files generated by this downloader only, matched to saved catalog
// IDs; do not guess metadata for personal music or follow symlinks.
func (s *server) repairDownloads(ctx context.Context) (int, int) {
	matched, repaired := 0, 0
	for _, source := range []string{"netease", "qq", "kugou"} {
		root, e := s.cardRoot()
		if e != nil {
			continue
		}
		lists := filepath.Join(root, "在线音频缓存", platformDirectory(source), "列表")
		dir := filepath.Join(root, "流媒体下载", platformDirectory(source))
		actual, e := filepath.EvalSymlinks(dir)
		if e != nil || actual != dir {
			continue
		}
		actual, e = filepath.EvalSymlinks(lists)
		if e != nil || actual != lists {
			continue
		}
		var songs = map[string]model.Song{}
		entries, _ := os.ReadDir(lists)
		for _, entry := range entries {
			st, e := entry.Info()
			if e != nil || !st.Mode().IsRegular() || st.Size() > 2<<20 {
				continue
			}
			b, e := os.ReadFile(filepath.Join(lists, entry.Name()))
			var c cachedLibrary
			if e != nil || json.Unmarshal(b, &c) != nil {
				continue
			}
			for _, song := range c.Result.Songs {
				songs[song.ID] = song
			}
		}
		files, _ := os.ReadDir(dir)
		for _, f := range files {
			if ctx.Err() != nil {
				return matched, repaired
			}
			st, e := f.Info()
			if e != nil || !st.Mode().IsRegular() {
				continue
			}
			ext := filepath.Ext(f.Name())
			if ext != ".flac" && ext != ".mp3" {
				continue
			}
			stem := strings.TrimSuffix(f.Name(), ext)
			i := strings.LastIndex(stem, " [")
			if i < 0 || !strings.HasSuffix(stem, "]") {
				continue
			}
			id := stem[i+2 : len(stem)-1]
			song, ok := songs[id]
			if !ok {
				continue
			}
			matched++
			path := filepath.Join(dir, f.Name())
			s.saveDownloadMetadata(ctx, downloadTask{song, source, "auto"}, song, path)
			if _, e = os.Stat(strings.TrimSuffix(path, ext) + ".jpg"); e == nil {
				repaired++
			}
		}
	}
	return matched, repaired
}

type flacBlock struct {
	kind byte
	data []byte
}

func flacPicture(jpg []byte) []byte {
	var b bytes.Buffer
	put := func(v uint32) { binary.Write(&b, binary.BigEndian, v) }
	put(3)
	put(10)
	b.WriteString("image/jpeg")
	put(0)
	put(480)
	put(480)
	put(24)
	put(0)
	put(uint32(len(jpg)))
	b.Write(jpg)
	return b.Bytes()
}
func flacComment(song model.Song) []byte {
	b, _ := mergeVorbisComment(nil, song)
	return b
}
func writeFLACMetadata(out io.Writer, in io.Reader, song model.Song, cover []byte) error {
	magic := make([]byte, 4)
	if _, e := io.ReadFull(in, magic); e != nil || string(magic) != "fLaC" {
		return errors.New("invalid FLAC")
	}
	var blocks []flacBlock
	total := 0
	haveComment, haveCover := false, false
	for {
		h := make([]byte, 4)
		if _, e := io.ReadFull(in, h); e != nil {
			return e
		}
		n := int(h[1])<<16 | int(h[2])<<8 | int(h[3])
		total += n + 4
		if total > 8<<20 || len(blocks) > 128 {
			return errors.New("FLAC metadata limit")
		}
		data := make([]byte, n)
		if _, e := io.ReadFull(in, data); e != nil {
			return e
		}
		kind := h[0] & 127
		if len(blocks) == 0 && (kind != 0 || n != 34) {
			return errors.New("FLAC missing STREAMINFO")
		}
		if kind == 4 {
			if haveComment {
				return errors.New("duplicate FLAC comment block")
			}
			merged, err := mergeVorbisComment(data, song)
			if err != nil {
				return err
			}
			data = merged
			haveComment = true
		}
		if kind == 6 {
			haveCover = true
		}
		blocks = append(blocks, flacBlock{kind, data})
		if h[0]&128 != 0 {
			break
		}
	}
	if !haveComment {
		blocks = append(blocks, flacBlock{4, flacComment(song)})
	}
	if !haveCover && len(cover) > 0 {
		blocks = append(blocks, flacBlock{6, flacPicture(cover)})
	}
	total = 0
	for _, b := range blocks {
		total += 4 + len(b.data)
	}
	if total > 8<<20 {
		return errors.New("FLAC metadata limit")
	}
	if _, e := out.Write(magic); e != nil {
		return e
	}
	for i, b := range blocks {
		n := len(b.data)
		kind := b.kind
		if i == len(blocks)-1 {
			kind |= 128
		}
		if _, e := out.Write([]byte{kind, byte(n >> 16), byte(n >> 8), byte(n)}); e != nil {
			return e
		}
		if _, e := out.Write(b.data); e != nil {
			return e
		}
	}
	_, e := io.CopyBuffer(out, in, make([]byte, 32768))
	return e
}
func syncSafe(b []byte) (int, error) {
	n := 0
	for _, v := range b {
		if v&128 != 0 {
			return 0, errors.New("invalid ID3 size")
		}
		n = n<<7 | int(v)
	}
	return n, nil
}
func syncSize(n int) []byte {
	return []byte{byte(n>>21) & 127, byte(n>>14) & 127, byte(n>>7) & 127, byte(n) & 127}
}
func id3Frame(version byte, id string, data []byte) []byte {
	b := append([]byte(id), make([]byte, 6)...)
	if version == 4 {
		copy(b[4:8], syncSize(len(data)))
	} else {
		binary.BigEndian.PutUint32(b[4:8], uint32(len(data)))
	}
	return append(b, data...)
}
func writeMP3Metadata(out io.Writer, in io.ReadSeeker, song model.Song, cover []byte) error {
	h := make([]byte, 10)
	n, e := io.ReadFull(in, h)
	if e != nil && n < 3 {
		return e
	}
	version := byte(3)
	var existing []byte
	if string(h[:3]) == "ID3" {
		if h[3] != 3 && h[3] != 4 || h[5] != 0 {
			return errors.New("unsupported existing ID3 flags/version")
		}
		version = h[3]
		size, e := syncSafe(h[6:10])
		if e != nil || size > 4<<20 {
			return errors.New("ID3 limit")
		}
		existing = make([]byte, size)
		if _, e = io.ReadFull(in, existing); e != nil {
			return e
		}
	} else {
		if _, e = in.Seek(0, io.SeekStart); e != nil {
			return e
		}
	}
	// Keep all original frames, discarding padding only. Validate frame boundaries
	// before appending; unusual tags fall back to the same-basename JPEG/LRC.
	pos := 0
	type savedFrame struct {
		id        string
		raw, data []byte
		key       string
		present   bool
	}
	var frames []savedFrame
	for pos < len(existing) && existing[pos] != 0 {
		if len(existing)-pos < 10 {
			return errors.New("short ID3 frame")
		}
		header := existing[pos : pos+10]
		id := string(header[:4])
		for _, c := range id {
			if !(c >= 'A' && c <= 'Z' || c >= '0' && c <= '9') {
				return errors.New("invalid ID3 frame")
			}
		}
		size := int(binary.BigEndian.Uint32(header[4:8]))
		if version == 4 {
			size, e = syncSafe(header[4:8])
			if e != nil {
				return e
			}
		}
		if size < 0 || size > len(existing)-pos-10 {
			return errors.New("invalid ID3 length")
		}
		data := existing[pos+10 : pos+10+size]
		key := id
		present := true
		if header[8] == 0 && header[9] == 0 {
			if id == "TXXX" {
				desc, value := splitID3Description(data)
				key = "TXXX:" + strings.ToUpper(desc)
				present = decodeID3Text(value) != ""
			} else if strings.HasPrefix(id, "T") {
				present = decodeID3Text(data) != ""
			} else if (id == "COMM" || id == "USLT") && len(data) >= 4 {
				encoded := append([]byte{data[0]}, data[4:]...)
				_, value := splitID3Description(encoded)
				present = decodeID3Text(value) != ""
			}
		}
		frames = append(frames, savedFrame{id, existing[pos : pos+10+size], data, key, present})
		pos += 10 + size
	}
	have := map[string]bool{}
	for _, f := range frames {
		if f.present {
			have[f.key] = true
		}
	}
	tags := knownSongTags(song)
	var added []byte
	replaced := map[string]bool{}
	for _, t := range tags {
		if t.key == "TRACKNUMBER" || t.key == "DISCNUMBER" {
			totalKey := "TRACKTOTAL"
			if t.key == "DISCNUMBER" {
				totalKey = "DISCTOTAL"
			}
			for _, total := range tags {
				if total.key == totalKey {
					t.value += "/" + total.value
					break
				}
			}
		}
		id, data := id3TagFrame(version, t)
		if id == "" {
			continue
		}
		key := id
		if id == "TXXX" {
			desc, _ := splitID3Description(data)
			key = "TXXX:" + strings.ToUpper(desc)
		}
		replaced[key] = true
		if !have[key] {
			added = append(added, id3Frame(version, id, data)...)
			have[key] = true
		}
		if t.key == "DATE" && version == 3 && len(t.value) > 4 {
			dateID, dateData := id3TagFrame(version, songTag{"RELEASEDATE", t.value})
			dateKey := "TXXX:RELEASEDATE"
			if !have[dateKey] {
				added = append(added, id3Frame(version, dateID, dateData)...)
				have[dateKey] = true
				replaced[dateKey] = true
			}
		}
	}
	var tag []byte
	for _, f := range frames {
		if replaced[f.key] && !f.present {
			continue
		}
		tag = append(tag, f.raw...)
	}
	tag = append(tag, added...)
	if !have["APIC"] && len(cover) > 0 {
		data := append([]byte{0}, []byte("image/jpeg\x00\x03\x00")...)
		data = append(data, cover...)
		tag = append(tag, id3Frame(version, "APIC", data)...)
	}
	if len(tag) > 4<<20 {
		return errors.New("ID3 limit")
	}
	header := append([]byte{'I', 'D', '3', version, 0, 0}, syncSize(len(tag))...)
	if _, e = out.Write(header); e != nil {
		return e
	}
	if _, e = out.Write(tag); e != nil {
		return e
	}
	_, e = io.CopyBuffer(out, in, make([]byte, 32768))
	return e
}
func embedDownloadMetadata(path string, song model.Song, cover []byte) error {
	ext := filepath.Ext(path)
	if ext != ".flac" && ext != ".mp3" {
		return nil
	}
	st, e := os.Lstat(path)
	if e != nil || !st.Mode().IsRegular() {
		return errors.New("nonregular download")
	}
	in, e := os.Open(path)
	if e != nil {
		return e
	}
	defer in.Close()
	out, e := os.CreateTemp(filepath.Dir(path), ".disc-tags-")
	if e != nil {
		return e
	}
	defer os.Remove(out.Name())
	defer out.Close()
	if ext == ".flac" {
		e = writeFLACMetadata(out, in, song, cover)
	} else {
		e = writeMP3Metadata(out, in, song, cover)
	}
	if e != nil {
		return e
	}
	if e = out.Sync(); e != nil {
		return e
	}
	if e = out.Close(); e != nil {
		return e
	}
	return os.Rename(out.Name(), path)
}
